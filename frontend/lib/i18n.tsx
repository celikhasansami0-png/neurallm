const DICTS: Record<LangCode, Dict> = { en, tr, ar, fr, de, es };

function getUserKey(): string {
  if (typeof window === "undefined") return "anon";
  try {
    const token = window.localStorage.getItem("phratic_token");
    if (!token) return "anon";
    const payload = JSON.parse(atob(token.split(".")[1].replace(/-/g, "+").replace(/_/g, "/")));
    return payload.sub || payload.email || "anon";
  } catch {
    return "anon";
  }
}

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  dir: "ltr" | "rtl";
  currency: string;
  formatMoney: (amount: number) => string;
};
const LanguageContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const key = `phratic_lang_${getUserKey()}`;
    const stored = window.localStorage.getItem(key) as LangCode | null;
    if (stored && DICTS[stored]) setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGS.includes(lang) ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (l: LangCode) => {
    setLangState(l);
    const key = `phratic_lang_${getUserKey()}`;
    window.localStorage.setItem(key, l);
  };

  const value = useMemo<Ctx>(() => ({
    lang,
    setLang,
    dir: RTL_LANGS.includes(lang) ? "rtl" : "ltr",
    currency: CURRENCY_BY_LANG[lang],
    formatMoney: (amount: number) => formatCurrency(amount, lang),
    t: (key: string, vars?: Record<string, string | number>) => {
      let str = DICTS[lang][key] || DICTS.en[key] || key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(`{${k}}`, String(v));
        }
      }
      return str;
    },
  }), [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}
