// Currency shown throughout the app is derived from the selected language.
export const CURRENCY_BY_LANG: Record<LangCode, string> = {
  tr: "TRY", en: "USD", ar: "USD", fr: "EUR", de: "EUR", es: "EUR",
};

export function formatCurrency(amount: number, lang: LangCode): string {
  const currency = CURRENCY_BY_LANG[lang] || "USD";
  try {
    return new Intl.NumberFormat(lang === "en" ? "en-US" : lang, { style: "currency", currency }).format(amount);
  } catch {
    return `${amount.toFixed(2)} ${currency}`;
  }
}

